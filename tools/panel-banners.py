"""Make each control panel's banner picture: its icon standing on the closed control carpet.

IRIX's control panels showed their own icon on the closed control panel carpet in the corner
of the window, as one picture. Both halves are IRIX exports drawn in the same frame -- a 50pt
square, `scale(0.5)` over a 100-unit field -- so the merge is the carpet's drawing with the
icon's laid on top of it, nothing rescaled. The result goes to the panel's `Assets/banner.svg`,
which `Wlrix.Theme.IrixPicture` draws.

Run from the repository root after changing a panel's icon or the carpet:

    python3 tools/panel-banners.py
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CARPET = ROOT / "src/Wlrix.IconCatalog/Assets/Carpets/control.closed.svg"
NAMESPACE = "http://www.w3.org/2000/svg"

# Project, and the icon in its data/icons that stands on the carpet.
PANELS = [
    ("Wlrix.Settings.Mouse", "com.wlrix.settings.mouse"),
    ("Wlrix.Settings.Keyboard", "com.wlrix.settings.keyboard"),
    ("Wlrix.Settings.Displays", "com.wlrix.settings.displays"),
    ("Wlrix.Settings.Login", "com.wlrix.settings.login"),
    ("Wlrix.Settings.Users", "com.wlrix.settings.users"),
    ("Wlrix.Settings.Sound", "com.wlrix.settings.sound"),
    ("Wlrix.Settings.Schemes", "com.wlrix.settings.schemes"),
    ("Wlrix.Settings.Windows", "com.wlrix.settings.windows"),
    ("Wlrix.Settings.Background", "com.wlrix.settings.background"),
    ("Wlrix.Settings.Bluetooth", "com.wlrix.settings.bluetooth"),
    ("Wlrix.Settings.Power", "com.wlrix.settings.power"),
    ("Wlrix.Settings.Network", "com.wlrix.settings.network"),
    ("Wlrix.Settings.Utilities", "com.wlrix.settings.utilities"),
]

ROOT_ELEMENT = re.compile(r"<svg\b[^>]*>", re.S)


def body(svg: str, name: str) -> tuple[str, str]:
    """The root element and everything inside it, of an IRIX-frame drawing."""
    root = ROOT_ELEMENT.search(svg)
    end = svg.rfind("</svg>")
    if not root or end < 0:
        sys.exit(f"{name}: not an SVG")
    tag = root.group(0)
    if 'width="50pt"' not in tag or 'height="50pt"' not in tag or 'viewBox="0 0 50 50"' not in tag:
        sys.exit(f"{name}: not drawn in the IRIX carpet frame, so it cannot be laid over the carpet")
    return tag, svg[root.end():end].strip("\n")


def main() -> None:
    carpet_tag, carpet = body(CARPET.read_text(), CARPET.name)
    if "xmlns=" not in carpet_tag:
        carpet_tag = carpet_tag.replace("<svg", f'<svg xmlns="{NAMESPACE}"', 1)
    for project, icon in PANELS:
        source = ROOT / "src" / project / "data" / "icons" / f"{icon}.svg"
        _, drawing = body(source.read_text(), source.name)
        out = ROOT / "src" / project / "Assets" / "banner.svg"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(
            '<?xml version="1.0" standalone="no"?>\n'
            f"<!-- Generated by tools/panel-banners.py from {CARPET.name} and {source.name}. -->\n"
            f"{carpet_tag}\n{carpet}\n{drawing}\n</svg>\n"
        )
        print(f"wrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
